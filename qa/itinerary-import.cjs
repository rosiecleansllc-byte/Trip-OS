const assert = require('node:assert/strict')
const {parseItinerary, validateItineraryRow, itineraryKey, draftToInput} = require('../src/lib/itineraryImport.ts')
const rows = parseItinerary(`MONDAY · NOV 9\nOcean day\nLIMA, PERU · DAY 5\nBREAKFAST\nCafe Sample\nACTIVITIES\nParagliding — weather permitting\nDINNER — CHOOSE ONE\nRestaurant One\nAlternative: Restaurant Two\nTUESDAY · NOV 10\nArt day\n8:15 PM\nFountain show\nConfirm fountain showtime before going.`, '2026-11-05')
