assert.equal(rows[1].date,'2026-11-09')
assert.equal(rows[1].time,'')
assert.equal(rows[2].selected,false)
assert.equal(rows[3].selected,false)
assert.equal(rows[4].time,'20:15')
assert.equal(rows[4].date,'2026-11-10')
