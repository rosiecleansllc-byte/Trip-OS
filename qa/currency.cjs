const { convertCurrency, convertTotals, parseExchangeRates } = require('../src/lib/exchangeRates.ts')
const { formatMoney, sumMoney } = require('../src/lib/money.ts')
const rates = { USD: 1, PEN: 3.450392, EUR: 0.897215 }
