assert(Math.abs(convertCurrency(1832.158152, 'PEN', 'USD', rates) - 531) < 1e-8)
assert.equal(convertCurrency(531, 'USD', 'USD'), 531)
assert.equal(convertCurrency(531, 'USD', 'BAD', rates), undefined)
assert.equal(convertCurrency(NaN, 'USD', 'PEN', rates), undefined)
assert.equal(convertTotals({ USD: 100, PEN: 3.450392 }, 'USD', rates), 101)
assert.equal(convertTotals({ BAD: 5 }, 'USD', rates), undefined)
